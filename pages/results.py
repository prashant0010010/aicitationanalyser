import json
from dataclasses import asdict

import streamlit as st

from components.ui import demo_banner, get_session, next_step, page_header, require, workflow_tracker
from config.scoring import PILLARS
from config.lexicons import SOURCE_TYPE_LABELS

s = get_session()
page_header("Results", "Review the evidence behind the Citation Quality Score and the 16 underlying metrics.")
workflow_tracker(s)
demo_banner(s)
require(s, "analysed")
r, sc = s.results, s.results.scoring


def fmt(v):
    return "n/a" if v is None else f"{v:.0f}"


top = st.columns(5)
top[0].metric("Citation Quality Score", fmt(sc["overall"]) + " / 100", sc["band"], delta_color="off")
for col, (k, v) in zip(top[1:], sc["pillars"].items()):
    col.metric(PILLARS[k]["short"], fmt(v["score"]), f"{v['available']} of {v['total']} metrics", delta_color="off")
if sc["provisional"]:
    st.warning("The score is provisional. " + " ".join(sc["notes"]))
st.caption(f"Query intent: {r.intent}. Semantic backend: {r.semantic_backend}. {r.ai_status}")

st.subheader("The 16 metrics")
st.dataframe([{"#": m.id, "Metric": m.name, "Pillar": PILLARS[m.pillar]["short"], "Score": m.score, "Basis": m.status} for m in r.metrics],
             hide_index=True, width="stretch",
             column_config={"Score": st.column_config.ProgressColumn("Score", min_value=0, max_value=100, format="%.0f")})

st.subheader("Evidence by metric")
for pk, pm in PILLARS.items():
    st.markdown(f"**{pm['name']}**")
    for m in [x for x in r.metrics if x.pillar == pk]:
        label = f"{m.id}. {m.name}: {fmt(m.score)}/100 ({m.status})"
        with st.expander(label):
            st.markdown("**Evidence**")
            for e in m.evidence:
                st.write("- " + e)
            st.markdown("**How it was calculated**")
            st.write(m.method)
            if m.components:
                st.caption("Components: " + ", ".join(f"{k.replace('_', ' ')} {v:.0f}" for k, v in m.components.items() if isinstance(v, (int, float))))
            st.markdown("**Interpretation**")
            st.write(m.interpretation or "Not available.")
            st.markdown("**Recommendation**")
            if m.recommendations:
                for x in m.recommendations:
                    st.write("- " + x)
            else:
                st.write("No action needed at this score." if m.available else "Supply the missing evidence to score this metric.")

with st.expander("How the score was calculated"):
    for line in sc["trace"]:
        st.code(line, language=None)

if len(r.query_set) > 1:
    st.subheader("Query set")
    st.dataframe([{"Query": q.query + (" (primary)" if q.is_primary else ""), "Score": q.overall, "Direct answer": q.key_metrics.get("Direct answer"),
                   "Coverage": q.key_metrics.get("Coverage"), "Relevance": q.key_metrics.get("Contextual relevance")} for q in r.query_set],
                 hide_index=True, width="stretch")

st.subheader("Entities")
st.dataframe([{"Entity": e["name"], "Type": e["type"].replace("_", " ").title(), "Role": e["role"], "Mentions": e["count"]} for e in r.entities],
             hide_index=True, width="stretch")
if r.relationships:
    st.markdown("**Relationships involving the target**")
    st.dataframe([{"Relation": x["relation"], "Counterpart": x["object"], "Evidence": x["sentence"]} for x in r.relationships], hide_index=True, width="stretch")
if r.facets:
    with st.expander("Subtopic coverage checklist"):
        st.dataframe([{"Subtopic": f["name"], "Status": f["level"], "Origin": f["origin"], "Best similarity": f["best_similarity"]} for f in r.facets], hide_index=True, width="stretch")
if r.external_summary:
    with st.expander("External sources"):
        st.dataframe([{"Source": e["label"] or e["url"], "Type": SOURCE_TYPE_LABELS.get(e["source_type"], e["source_type"]), "Read": e["ok"], "Mentions": e["mentions"],
                       "Links to site": e["links_to_target"], "Prominent": e["prominent"]} for e in r.external_summary], hide_index=True, width="stretch")
if r.ai_commentary:
    st.subheader("AI-generated commentary")
    st.caption(f"Generated by {r.ai_provider}. It does not change any score. Review before use.")
    st.write(r.ai_commentary["summary"])
    for x in r.ai_commentary["priorities"]:
        st.write("- " + x)

st.download_button("Download results as JSON", data=json.dumps(asdict(r), indent=2, default=str), file_name="ai_citation_results.json", mime="application/json")
next_step("Next, see the prioritised actions and citation opportunities.", "opps", "Go to Citation Opportunities")
